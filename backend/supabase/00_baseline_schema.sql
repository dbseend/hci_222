-- The live project predates auth_ownership_hardening.sql: it still carries the
-- permissive grants/policies below, which that migration revokes.
create extension if not exists citext;
create extension if not exists pgcrypto;

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  code text unique,
  name text not null,
  default_unit text not null default 'kg',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.markets (
  id uuid primary key default gen_random_uuid(),
  name citext not null unique,
  company_name text,
  country_code text not null default 'EG',
  city text,
  district text,
  lat double precision,
  lng double precision,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.purchases (
  id uuid primary key default gen_random_uuid(),
  auth_user_id uuid references auth.users(id),
  client_user_id text not null,
  product_id uuid not null references public.products(id),
  market_id uuid references public.markets(id),
  product_name_override text,
  store_name_override text,
  location_override text,
  unit text not null default 'kg',
  quantity numeric not null default 1,
  final_price_egp numeric not null check (final_price_egp >= 0),
  detected_price_egp numeric check (detected_price_egp is null or detected_price_egp >= 0),
  image_path text,
  created_at timestamptz not null default now()
  -- price_observation_id is added by price_data_mvp.sql
);

create table if not exists public.community_posts (
  id uuid primary key default gen_random_uuid(),
  purchase_id uuid not null unique references public.purchases(id),
  auth_user_id uuid references auth.users(id),
  client_user_id text not null,
  product_id uuid not null references public.products(id),
  market_id uuid references public.markets(id),
  product_name_cache text not null,
  store_name_cache text not null,
  location_cache text not null,
  price_egp numeric not null check (price_egp >= 0),
  image_path text,
  created_at timestamptz not null default now()
);

create table if not exists public.scan_histories (
  id uuid primary key default gen_random_uuid(),
  auth_user_id uuid references auth.users(id),
  client_user_id text not null,
  image_path text not null,
  created_at timestamptz not null default now()
  -- detection/price columns are added by scan_history_cache.sql
);

create table if not exists public.exchange_rates (
  id bigint generated by default as identity primary key,
  base_currency text not null,
  quote_currency text not null,
  rate numeric not null check (rate > 0),
  as_of_date date not null,
  source text,
  created_at timestamptz not null default now(),
  unique (base_currency, quote_currency, as_of_date)
);

create index if not exists idx_products_code on public.products (code);
create index if not exists idx_markets_name on public.markets (name);
create index if not exists idx_purchases_product_created_at on public.purchases (product_id, created_at desc);
create index if not exists idx_purchases_client_created_at on public.purchases (client_user_id, created_at desc);
create index if not exists idx_scan_histories_client_created_at on public.scan_histories (client_user_id, created_at desc);
create index if not exists idx_community_posts_created_at on public.community_posts (created_at desc);
create index if not exists idx_community_posts_product_cache on public.community_posts (lower(product_name_cache));
create index if not exists idx_community_posts_store_cache on public.community_posts (lower(store_name_cache));
create index if not exists idx_community_posts_location_cache on public.community_posts (lower(location_cache));
create index if not exists idx_exchange_rates_pair_date on public.exchange_rates (base_currency, quote_currency, as_of_date desc);

create or replace view public.community_feed_v1 as
select id, purchase_id, auth_user_id, client_user_id, product_id, market_id,
       product_name_cache as product_name,
       store_name_cache as store_name,
       location_cache as location_name,
       price_egp, image_path, created_at
from public.community_posts cp
order by created_at desc;

insert into storage.buckets (id, name, public)
values ('community-images', 'community-images', true),
       ('scan-history-images', 'scan-history-images', false)
on conflict (id) do nothing;

